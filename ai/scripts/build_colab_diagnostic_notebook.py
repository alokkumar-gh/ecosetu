            '# 5. Inference Engine & IoU Matching Algorithm\n',
            'def box_iou(box1, box2):\n',
            '    # box: [xc, yc, w, h] normalized\n',
            '    x1_min = box1[0] - box1[2] / 2\n',
            '    y1_min = box1[1] - box1[3] / 2\n',
